package com.mihomo.tproxy.core

import android.content.Context
import com.mihomo.tproxy.model.ProxySettings
import java.io.File
import java.util.zip.GZIPInputStream

/**
 * Owns the on-device runtime: binary, geo databases, generated config, control
 * script and the boot hook. Everything privileged goes through RootShell.
 */
class CoreManager(private val ctx: Context) {

    companion object {
        const val DIR = "/data/adb/mihomo_tproxy"
        const val BIN = "$DIR/bin/mihomo"
        const val CONFIG = "$DIR/data/config.yaml"
        const val LOG = "$DIR/logs/core.log"
        const val CTL = "$DIR/ctl.sh"
        const val VERSION_TAG = "1.19.14"
        const val BOOT_SCRIPT = "/data/adb/service.d/99-mihomo-tproxy.sh"
    }

    private val stage: File by lazy {
        File(ctx.getExternalFilesDir(null) ?: ctx.filesDir, "stage").apply { mkdirs() }
    }

    fun ensureDirs(): Boolean =
        RootShell.exec("mkdir -p $DIR/bin $DIR/geo $DIR/config $DIR/logs $DIR/run $DIR/data && chmod 755 $DIR $DIR/bin").ok

    fun binaryExists(): Boolean = RootShell.exec("test -x " + BIN + " && echo yes", 8).out.contains("yes")

    fun installedVersion(): String {
        val r = RootShell.exec("cat $DIR/.version 2>/dev/null", 8)
        return r.out.trim()
    }

    fun installCore(onStep: (String) -> Unit): Result<String> {
        if (!RootShell.hasRoot()) return Result.failure(Exception("未获得 Root 权限"))
        onStep("准备目录")
        if (!ensureDirs()) return Result.failure(Exception("无法创建运行时目录"))
        if (installedVersion() != VERSION_TAG) {
            onStep("写入 mihomo 内核 (arm64)")
            val ok = pushAssetGz("mihomo.gz", "$DIR/bin/mihomo", 0b111101101) // 0755
            if (!ok) return Result.failure(Exception("内核安装失败"))
            RootShell.exec("echo '" + VERSION_TAG + "' > $DIR/.version")
        }
        onStep("写入 geo 数据库")
        pushAssetRaw("geoip.metadb", "$DIR/data/geoip.metadb", 0b110100100)
        pushAssetRaw("geosite.dat", "$DIR/data/geosite.dat", 0b110100100)
        onStep("写入控制脚本")
        val ctl = ctx.assets.open("ctl.sh").readBytes()
        pushBytes("$DIR/ctl.sh", ctl, 0b111101101)
        if (!File(LOG).exists()) RootShell.exec("touch $LOG")
        onStep("完成")
        return Result.success("内核 " + VERSION_TAG + " 就绪")
    }

    /** Replaces the core binary from a downloaded .gz asset. */
    fun installBinaryGz(gz: ByteArray, version: String): Boolean {
        val raw = runCatching {
            java.util.zip.GZIPInputStream(gz.inputStream()).use { it.readBytes() }
        }.getOrNull() ?: return false
        if (raw.size < 1_000_000) return false
        if (!pushBytes(BIN, raw, 0b111101101)) return false
        RootShell.exec("echo '" + version.removePrefix("v") + "' > " + DIR + "/.version")
        return true
    }

    /** Runs "mihomo -t" so a broken subscription can never take the running core down. */
    fun validateConfig(yaml: String): Pair<Boolean, String> {
        if (!pushBytes(DIR + "/data/.validate.yaml", yaml.toByteArray(), 0b110100100)) {
            return false to "无法写入校验文件"
        }
        val r = RootShell.exec(BIN + " -t -d " + DIR + "/data -f " + DIR + "/data/.validate.yaml 2>&1", 45)
        val out = r.out.trim()
        val ok = out.contains("test is successful")
        return ok to out
    }

    fun writeConfig(yaml: String): Boolean {
        if (!pushBytes(CONFIG, yaml.toByteArray(), 0b110100100)) return false
        return true
    }

    fun readConfig(): String = RootShell.exec("cat $CONFIG 2>/dev/null", 10).out

    fun start(): ShellResult = RootShell.exec("sh $CTL start", 25)

    fun stop(): ShellResult = RootShell.exec("sh $CTL stop", 25)

    fun status(): Boolean = RootShell.exec("sh $CTL status", 10).out.contains("running")

    fun corePid(): String = RootShell.exec("cat $DIR/run/core.pid 2>/dev/null", 8).out.trim()

    fun tailLog(lines: Int = 200): String =
        RootShell.exec("tail -n " + lines + " $LOG 2>/dev/null", 10).out

    fun clearLog() { RootShell.exec(": > $LOG") }

    fun setBootStart(enabled: Boolean, settings: ProxySettings): Boolean {
        if (!enabled) {
            RootShell.exec("rm -f $BOOT_SCRIPT " + DIR + "/auto_start")
            return true
        }
        pushBytes(DIR + "/auto_start", "1".toByteArray(), 0b110100100)
        val script = """
            #!/system/bin/sh
            # generated by Mihomo TProxy
            sleep 25
            sh $CTL start
        """.trimIndent() + "\n"
        val ok = pushBytes(BOOT_SCRIPT, script.toByteArray(), 0b111101101)
        return ok
    }

    fun uninstallCore() {
        RootShell.exec("sh $CTL stop 2>/dev/null; rm -rf $DIR; rm -f $BOOT_SCRIPT")
    }

    // ---------- privileged file push ----------

    private fun pushAssetGz(asset: String, dest: String, mode: Int): Boolean {
        val tmp = File(stage, "core.tmp")
        return runCatching {
            ctx.assets.open(asset).use { input ->
                GZIPInputStream(input).use { gz -> tmp.outputStream().use { gz.copyTo(it) } }
            }
            pushFile(tmp, dest, mode)
        }.getOrDefault(false)
    }

    private fun pushAssetRaw(asset: String, dest: String, mode: Int): Boolean {
        val tmp = File(stage, File(asset).name)
        return runCatching {
            ctx.assets.open(asset).use { input -> tmp.outputStream().use { input.copyTo(it) } }
            pushFile(tmp, dest, mode)
        }.getOrDefault(false)
    }

    private fun pushFile(src: File, dest: String, mode: Int): Boolean {
        val staged = src.absolutePath
        val oct = Integer.toOctalString(mode)
        val r = RootShell.exec(
            "mkdir -p \$(dirname '" + dest + "') && cp -f '" + staged + "' '" + dest + "' && chmod " + oct + " '" + dest + "'",
            90
        )
        if (r.ok && sizeOf(dest) == src.length()) return true
        return pushStdin(dest, src.readBytes(), mode)
    }

    fun pushBytes(dest: String, bytes: ByteArray, mode: Int = 0b110100100): Boolean {
        if (pushStdin(dest, bytes, mode) && sizeOf(dest) == bytes.size.toLong()) return true
        val f = File(stage, "upload.tmp")
        return runCatching { f.writeBytes(bytes); pushFile(f, dest, mode) }.getOrDefault(false)
    }

    private fun pushStdin(dest: String, bytes: ByteArray, mode: Int): Boolean {
        val oct = Integer.toOctalString(mode)
        val cmd = "mkdir -p \$(dirname '" + dest + "') && cat > '" + dest + "' && chmod " + oct + " '" + dest + "'"
        return RootShell.exec(cmd, 240, bytes).ok
    }

    private fun sizeOf(dest: String): Long =
        RootShell.exec("wc -c < '" + dest + "' 2>/dev/null", 10).out.trim().toLongOrNull() ?: -1L
}